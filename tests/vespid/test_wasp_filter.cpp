/**
 * test_wasp_filter.cpp — Behavioral tests for src/vespid/WaspFilter.hpp
 *
 * TDD behavioral suite for the Wasp VCF nonlinear core (Task 3).  The core is
 * driven directly at fsInt = 192000 (standing in for 48 kHz host x 4), no
 * resamplers.  Controls are wired exactly like wasp_ref.py's set_controls:
 *     fci = clamp(fc*wcComp, 0.25, 0.45*fsInt)
 *     g   = tan(pi*fci/fsInt)
 *     wci = 2*pi*fci
 *     kC2 = R3*C2*wci - kR2*wci/(2*pi*fPole)   (may be negative)
 *     h1  = computeH1(rho, fsInt)
 *
 * Golden numbers are the committed values in tests/vespid_ref/golden.json
 * (generated by wasp_ref.py at 48 kHz x8 = 384 kHz with the brentq solver).
 * They are RAW states (pre-makeup, pre-DC-blocker): small-signal on raw LP,
 * self-osc amplitude on raw BP.  We therefore measure WaspFilter::raw().
 *
 * Compile & run (or via tests/run.sh):
 *   g++ -std=c++20 -O2 -I../src -o test_wasp_filter test_wasp_filter.cpp && ./test_wasp_filter
 */

