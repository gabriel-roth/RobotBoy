static int sPassed = 0, sFailed = 0;
static void report(bool ok, const char* name, const char* detail = nullptr) {
    if (ok) { printf("  PASS  %s\n", name); ++sPassed; }
    else {
        printf("  FAIL  %s", name);
        if (detail) printf("  (%s)", detail);
        printf("\n"); ++sFailed;
    }
}

