// ── Control wiring (matches wasp_ref.py set_controls) ──────────────────────
static constexpr float kFsInt = 192000.f;   // 48 kHz x4 (brief)
static constexpr float kPi    = 3.14159265358979323846f;
static constexpr float kFPole = 80000.f;
static constexpr float kR3C2  = 27e3f * 100e-12f;   // 2.7e-6

struct Controls { float g; float kC2; wasp::H1Coeffs h1; };

static Controls makeControls(const wasp::ModeConfig& m, float fc, float rho) {
    float fci = fc * m.wcComp;
    float lo = 0.25f, hi = 0.45f * kFsInt;
    if (fci < lo) fci = lo;
    if (fci > hi) fci = hi;
    float g   = std::tan(kPi * fci / kFsInt);
    float wci = 2.f * kPi * fci;
    float kC2 = kR3C2 * wci - m.kR2 * wci / (2.f * kPi * kFPole);
    wasp::H1Coeffs h1 = wasp::computeH1(rho < 0.f ? 0.f : (rho > 1.f ? 1.f : rho), kFsInt);
    return { g, kC2, h1 };
}

// ── Small-signal RMS-ratio LP response (matches response_db) ───────────────
static double smallSignalLpDb(const wasp::ModeConfig& m, float fc, float rho,
                              float fprobe, float amp, bool highAcc = true) {
    wasp::WaspFilter w; w.setSampleRate(kFsInt); w.setMode(m); w.reset();
    Controls c = makeControls(m, fc, rho);
    const int n = (int)(kFsInt * 0.5f);
    std::vector<float> y(n);
    for (int i = 0; i < n; ++i) {
        float x = amp * std::sin(2.f * kPi * fprobe * (float)i / kFsInt);
        w.process(x, c.g, c.h1, c.kC2, highAcc);
        y[i] = w.raw().lp;
    }
    // RMS over 2nd half (mean removed like std) vs input RMS
    double sumY = 0, sumY2 = 0; int cnt = 0;
    for (int i = n / 2; i < n; ++i) { sumY += y[i]; sumY2 += (double)y[i]*y[i]; ++cnt; }
    double meanY = sumY / cnt;
    double stdY = std::sqrt(sumY2 / cnt - meanY * meanY);
    double stdRef = amp / std::sqrt(2.0);   // std of a unit-amp sine = amp/sqrt2
    return 20.0 * std::log10((std::sqrt(2.0) * stdY + 1e-12) / (std::sqrt(2.0) * stdRef));
}

// Same, but returns the makeup'd + DC-blocked output (for HP passband/makeup).
static double smallSignalDb(const wasp::ModeConfig& m, float fc, float rho,
                            float fprobe, float amp, int which /*0=lp,1=bp,2=hp*/) {
    wasp::WaspFilter w; w.setSampleRate(kFsInt); w.setMode(m); w.reset();
    Controls c = makeControls(m, fc, rho);
    const int n = (int)(kFsInt * 0.5f);
    std::vector<float> y(n);
    for (int i = 0; i < n; ++i) {
        float x = amp * std::sin(2.f * kPi * fprobe * (float)i / kFsInt);
        wasp::WaspFilter::Out o = w.process(x, c.g, c.h1, c.kC2, true);
        y[i] = which == 0 ? o.lp : (which == 1 ? o.bp : o.hp);
    }
    double sumY = 0, sumY2 = 0; int cnt = 0;
    for (int i = n / 2; i < n; ++i) { sumY += y[i]; sumY2 += (double)y[i]*y[i]; ++cnt; }
    double meanY = sumY / cnt;
    double stdY = std::sqrt(sumY2 / cnt - meanY * meanY);
    double stdRef = amp / std::sqrt(2.0);
    return 20.0 * std::log10((std::sqrt(2.0) * stdY + 1e-12) / (std::sqrt(2.0) * stdRef));
}

// ── Self-oscillation probe (matches selfosc_probe) ─────────────────────────
// Kick 0.1 s of 3 V sine at fc, then silence; measure raw BP tail (last 0.25 s):
// amplitude = sqrt(2)*std(mean-removed), frequency = positive-going zero xings.
struct SelfOsc { double amp; double freq; bool finite; };
static SelfOsc selfOsc(const wasp::ModeConfig& m, float fc, float rho, float dur) {
    wasp::WaspFilter w; w.setSampleRate(kFsInt); w.setMode(m); w.reset();
    Controls c = makeControls(m, fc, rho);
    const int n = (int)(kFsInt * dur);
    const int kick = (int)(kFsInt * 0.1f);
    std::vector<float> bp(n);
    bool finite = true;
    for (int i = 0; i < n; ++i) {
        float x = (i < kick) ? 3.f * std::sin(2.f * kPi * fc * (float)i / kFsInt) : 0.f;
        w.process(x, c.g, c.h1, c.kC2, true);
        bp[i] = w.raw().bp;
        if (!std::isfinite(bp[i])) finite = false;
    }
    int t0 = n - (int)(kFsInt * 0.25f);
    double sum = 0; int cnt = 0;
    for (int i = t0; i < n; ++i) { sum += bp[i]; ++cnt; }
    double mean = sum / cnt;
    double s2 = 0;
    for (int i = t0; i < n; ++i) { double d = bp[i] - mean; s2 += d * d; }
    double amp = std::sqrt(2.0) * std::sqrt(s2 / cnt);
    // positive-going zero crossings on the mean-removed tail
    std::vector<int> zc;
    for (int i = t0 + 1; i < n; ++i) {
        double a = bp[i - 1] - mean, b = bp[i] - mean;
        if (a <= 0 && b > 0) zc.push_back(i - t0);
    }
    double freq = 0;
    if ((int)zc.size() > 3)
        freq = kFsInt * (double)(zc.size() - 1) / (double)(zc.back() - zc.front());
    return { amp, freq, finite };
}

static bool withinDb(double a, double b, double tol) { return std::fabs(a - b) <= tol; }

