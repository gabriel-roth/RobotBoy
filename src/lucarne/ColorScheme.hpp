// Out-of-range indices give the first (Lucarne) scheme.
inline const ColorScheme& scheme(int index) {
	return kSchemes[(index >= 0 && index < kNumSchemes) ? index : 0];
}

// Index for a patch-stored id; null or unknown gives 0 (Lucarne).
inline int schemeFromPatch(const char* id) {
	if (!id) return 0;
	for (int i = 0; i < kNumSchemes; ++i)
		if (std::strcmp(kSchemes[i].id, id) == 0) return i;
	return 0;
}

